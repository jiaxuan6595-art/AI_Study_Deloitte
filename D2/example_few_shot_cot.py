"""
示例6：少样本学习 + 思维链 (Few-shot + Chain of Thought)

【什么是少样本+CoT？】
将少样本学习和思维链两种策略结合起来，发挥各自的优势：
- 少样本学习：提供示例，让模型学习期望的格式和推理模式
- 思维链：引导模型展示详细的推理过程

【为什么要结合？】
1. 示例可以告诉模型"应该如何思考"
2. 推理过程可以提高复杂问题的准确性
3. 输出格式更加可控和可解释

【适用场景】
- 需要特定推理模式的复杂问题
- 需要解释答案由来的场景
- 需要标准化输出格式的任务

【示例格式】
每个示例包含：问题、思考过程、最终答案
"""

